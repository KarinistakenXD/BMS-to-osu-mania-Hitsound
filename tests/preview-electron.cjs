const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const assert = require('node:assert/strict');
app.commandLine.appendSwitch('autoplay-policy', 'no-user-gesture-required');
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, webPreferences: { nodeIntegration: false, contextIsolation: true } });
  try {
    const html = fs.readFileSync('renderer/index.html', 'utf8').replace(/<script[^>]*src=[^>]*><\/script>/g, '');
    await window.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(html));
    await window.webContents.executeJavaScript(`window.bms2osu = { onLog: () => {}, checkFfmpeg: async () => ({ available: false }), ffmpegStatus: async () => ({ available: false }) }; void 0;`);
    const source = fs.readFileSync('renderer/renderer.ts', 'utf8');
    const test = `
      window.smoke = async () => {
        audioCtx = new AudioContext();
        state.targetAudioBuffer = audioCtx.createBuffer(2, audioCtx.sampleRate * 8, audioCtx.sampleRate);
        const sample = audioCtx.createBuffer(1, audioCtx.sampleRate / 10, audioCtx.sampleRate);
        sample.getChannelData(0).fill(.1);
        state.audioBuffers.set('01', sample);
        state.syncedEvents = [{ timeMs: 500, wavId: '01', lane: 0, isBgm: false }];
        state.songLengthMs = 8000; state.compatibilityOk = true;
        previewMode.value = 'target-plus-keys'; playbackRate.value = '1';
        metronomeEnabled.checked = false;
        keysInput.value = '15';
        const warming = warmPreview();
        const generation = preparationGeneration;
        keysInput.value = '18'; keysInput.dispatchEvent(new Event('input'));
        await warming;
        if (btnPlay.disabled || preparationGeneration !== generation) throw new Error('Key change during preparation locked Play');
        const bus = state.convertedMixBuffer;
        if (!bus) throw new Error('Bus not prepared');
        const ready = preparedPreviews.get(preparationKey('target-plus-keys', 1));
        state.sync = { mode: 'offset', offsetMs: 0, scale: 1 };
        state.analyzedReuseKey = 'same-song'; state.bmsPath = 'chart.bms';
        window.bms2osu.readOsuPreview = async () => ({ reuseKey: 'same-song', metadata: { title: 'Song', artist: 'Artist', creator: 'Mapper', version: 'Hard' }, timingPoints: [], osuPreview: { mode: 3, keys: 7, notes: [{ timeMs: 500, endTimeMs: 1500, lane: 2 }] } });
        resnap.checked = false;
        if (!await reuseAnalyzedTarget('Hard.osu')) throw new Error('Matching difficulty not reused');
        await Promise.resolve();
        if (btnPlay.disabled || state.convertedMixBuffer !== bus || state.targetKeys !== 7 || state.targetNotes[0].endTimeMs !== 1500 || state.osuPath !== 'Hard.osu') throw new Error('Reused difficulty did not stay ready or update notes');
        window.bms2osu.readOsuPreview = async () => ({ reuseKey: 'different-song' });
        if (await reuseAnalyzedTarget('Other.osu')) throw new Error('Unrelated map reused analysis');
        notePreviewSpeed.value = '1'; notePreviewSpeed.dispatchEvent(new Event('input'));
        if (!notePreviewSpeedOut.value.startsWith('1 · 11480')) throw new Error('Scroll speed 1 was clamped');
        notePreviewSpeed.value = '40'; notePreviewSpeed.dispatchEvent(new Event('input'));
        if (!notePreviewSpeedOut.value.startsWith('40 · 287')) throw new Error('Scroll speed 40 failed');
        keysInput.value = '15'; keysInput.dispatchEvent(new Event('input'));
        keysInput.value = '18'; keysInput.dispatchEvent(new Event('input'));
        if (btnPlay.disabled || state.convertedMixBuffer !== bus || preparedPreviews.get(preparationKey('target-plus-keys', 1)) !== ready) throw new Error('Ready key change invalidated audio');
        const started = performance.now();
        await startPreview(0);
        const playMs = performance.now() - started;
        if (!previewPlaying || !targetSource || !keyBusSource) throw new Error('Playback did not start');
        const clock = previewStartedAt;
        const playingSource = targetSource;
        keysInput.value = '15'; keysInput.dispatchEvent(new Event('input'));
        if (!previewPlaying || targetSource !== playingSource || previewStartedAt !== clock) throw new Error('Key change interrupted playback');
        stopPreview();
        const resumed = performance.now();
        await startPreview(2);
        const resumeMs = performance.now() - resumed;
        if (state.convertedMixBuffer !== bus || previewStartSec !== 2) throw new Error('Resume failed');
        const pending = startPreview(3); stopPreview(); await pending;
        if (previewPlaying) throw new Error('Cancelled Play restarted audio');
        resnap.checked = true;
        window.bms2osu.readOsuPreview = async () => ({ reuseKey: 'same-song', metadata: { title: 'Song', artist: 'Artist', creator: 'Mapper', version: 'Resnap' }, timingPoints: [], osuPreview: { mode: 3, keys: 7, notes: [{ timeMs: 510, endTimeMs: 1500, lane: 2 }] } });
        const decodedSong = state.targetAudioBuffer;
        const beforeResnap = preparationGeneration;
        if (!await reuseAnalyzedTarget('Resnap.osu')) throw new Error('Changed notes lost reusable alignment');
        await warmPreview();
        if (preparationGeneration === beforeResnap || state.convertedMixBuffer === bus || state.targetAudioBuffer !== decodedSong || btnPlay.disabled) throw new Error('Changed resnap did not prepare bus while preserving decoded song');
        return { playMs, resumeMs, sharedClock: clock > 0, busFrames: bus.length };
      };
    `;
    const bundled = esbuild.buildSync({ stdin: { contents: source + test, resolveDir: path.resolve('renderer'), loader: 'ts' }, bundle: true, write: false, format: 'iife' }).outputFiles[0].text;
    await window.webContents.executeJavaScript(bundled);
    const result = await window.webContents.executeJavaScript('window.smoke()');
    assert(result.playMs < 500 && result.resumeMs < 500);
    console.log('PASS: Windows Electron prepare, key changes during preparation/ready/playback, Play, resume, and cancellation', JSON.stringify(result));
    app.exit(0);
  } catch (error) { console.error(error); app.exit(1); }
});
